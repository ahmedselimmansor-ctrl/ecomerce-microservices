#!/usr/bin/env bash
# ============================================================================
#  حارس الترحيلات.
#
#  يمنع تعديل ترحيل سبق دمجه في main. Flyway يحفظ بصمة كل ملف طبّقه، فتغيير
#  حرف واحد فيه يوقف الخدمة على كل قاعدة قائمة بـ
#  «Migrations have failed validation».
#
#  ما يجعل الخطأ يمرّ إلى الإنتاج أن بيئة جديدة تعمل بلا شكوى: القاعدة
#  الفارغة تطبّق الملف المعدَّل وتحفظ بصمته الجديدة. البيئات القائمة وحدها
#  تسقط — أي أن اختبار CI على قاعدة نظيفة لا يراه.
#
#  لذلك الفحص هنا على git لا على قاعدة بيانات.
# ============================================================================
set -uo pipefail

cd "$(dirname "$0")/.."

BASE="${1:-origin/main}"
PATTERN='services/.*/db/migration/V.*\.sql$'

if ! git rev-parse --verify --quiet "${BASE}" >/dev/null; then
  echo "المرجع ${BASE} غير موجود — تخطّي الفحص"
  exit 0
fi

# M = معدَّل، D = محذوف، R = مُعاد تسميته. الإضافة (A) وحدها مسموحة.
#
# نقارن بـ `${BASE}` لا بـ `${BASE}...HEAD`: الصيغة الثلاثية تقارن الـ commits
# عند نقطة التفرّع فقط، فلا ترى تعديلًا في شجرة العمل لم يُودَع بعد — وهي
# اللحظة التي نريد أن نمسك فيها الخطأ. الصيغة المفردة تشمل المُودَع وغيره.
CHANGED=$(git diff --name-status --diff-filter=MDR "${BASE}" -- '*/db/migration/*.sql' \
          | awk '{print $1 "\t" $2}')

if [ -z "${CHANGED}" ]; then
  echo "✅ لا ترحيل مُطبَّق تغيّر"
  exit 0
fi

echo "❌ ترحيلات سبق دمجها تغيّرت:"
echo ""
printf '%s\n' "${CHANGED}" | while IFS=$'\t' read -r status file; do
  case "${status}" in
    M*) label="عُدِّل" ;;
    D*) label="حُذف" ;;
    R*) label="أُعيدت تسميته" ;;
    *)  label="${status}" ;;
  esac
  printf '   %-14s %s\n' "${label}" "${file}"
done

cat <<'EOF'

الترحيل المدموج لا يُعدَّل — بصمته محفوظة في كل قاعدة طُبِّق عليها.
أضف ترحيلًا جديدًا V<n>__… بـ ALTER TABLE بدلًا من ذلك.

التفاصيل: docs/03-data-model.md § قاعدة الترحيلات
EOF
exit 1
